#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
# shellcheck source=common.sh
source "$SCRIPT_DIR/common.sh"

ROOT="$(engineos_root)"
if [[ -n "${ENGINEOS_AGENT_INDEX:-}" ]]; then
  INDEX="$ENGINEOS_AGENT_INDEX"
elif [[ -f "$ROOT/.agents/index.toml" ]]; then
  INDEX="$ROOT/.agents/index.toml"
else
  INDEX="$ROOT/share/engineos/.agents/index.toml"
fi

usage() {
  cat <<'HELP'
Usage:
  agent_metadata.sh roles
  agent_metadata.sh profile <role>
  agent_metadata.sh wrapper <role>
  agent_metadata.sh write <out-root>
HELP
}

die() {
  printf 'agent metadata: %s\n' "$*" >&2
  exit 1
}

role_block() {
  local role="$1"
  awk -v role="$role" '
    /^\[\[roles\]\]/ { in_block = 0; block = ""; next }
    { block = block $0 "\n" }
    /^id = "/ {
      in_block = ($0 == "id = \"" role "\"")
    }
    in_block && /^route_triggers = / {
      print block
      exit
    }
  ' "$INDEX"
}

field() {
  local role="$1"
  local name="$2"
  role_block "$role" | awk -F'"' -v name="$name" '$1 == name " = " { print $2; exit }'
}

array_field() {
  local role="$1"
  local name="$2"
  role_block "$role" | awk -v name="$name" '$0 ~ "^" name " = " { sub("^" name " = ", ""); print; exit }'
}

roles() {
  awk -F'"' '/^id = "/ { print $2 }' "$INDEX"
}

profile() {
  local role="$1"
  local display mode role_doc skill wrapper triggers risk kind
  display="$(field "$role" display_name)"
  mode="$(field "$role" mode)"
  role_doc="$(field "$role" role_doc)"
  skill="$(field "$role" skill)"
  wrapper="$(field "$role" opencode_wrapper)"
  triggers="$(array_field "$role" route_triggers)"
  [[ -n "$display" ]] || die "unknown role: $role"
  risk="medium"
  kind="agent-handoff"
  [[ "$mode" == "primary" ]] && risk="low" && kind="agent-route"

  cat <<EOF
schema = "engineos-agent-profile-v0"
role = "$role"
display_name = "$display"
mode = "$mode"
risk_default = "$risk"
primary_skill = "$role"
role_doc = "$role_doc"
role_spec = "docs/agent-roles.md"
skill = "$skill"
opencode_wrapper = "$wrapper"
codex_entry = "AGENTS.md"
observability_kind = "$kind"
observability_policy = "metadata-only; no raw prompts or AI I/O"
route_triggers = $triggers
handoff_targets = ["oracle", "cleaner"]
proof_commands = ["eos-agent route --dry-run \"<request>\"", "eos-test agent"]
allowed_read = ["AGENTS.md", "CURRENT_STATUS.md", "ROADMAP.md", "docs/agent-roles.md", ".agents/roles/*/AGENTS.md", ".agents/skills/*/SKILL.md"]
ask_before = ["edit", "bash", "external_directory", "sudo", "install", "usb-write", "package-removal"]
forbidden = ["raw prompt storage", "project MCP CLI execution", "destructive action without user approval"]
EOF
}

wrapper() {
  local role="$1"
  local display mode skill role_doc
  display="$(field "$role" display_name)"
  mode="$(field "$role" mode)"
  skill="$(field "$role" skill)"
  role_doc="$(field "$role" role_doc)"
  [[ -n "$display" ]] || die "unknown role: $role"

  cat <<EOF
---
description: $display specialist generated from .agents/index.toml.
mode: $mode
permission:
  read: allow
  glob: allow
  grep: allow
  list: allow
  edit: ask
  bash: ask
  external_directory: ask
---

Use \`docs/agent-roles.md\`, \`$role_doc\`, and \`$skill\`.
Generated by \`tools/scripts/agent_metadata.sh\`; do not hand-edit.
EOF
}

write_all() {
  local out_root="$1"
  local role
  [[ -n "$out_root" ]] || die "write requires an output root"
  while IFS= read -r role; do
    [[ -n "$role" ]] || continue
    install -d -m 0755 "$out_root/.agents/profiles" "$out_root/.opencode/agents"
    profile "$role" >"$out_root/.agents/profiles/$role.profile.toml"
    wrapper "$role" >"$out_root/.opencode/agents/$role.md"
  done < <(roles)
}

cmd="${1:-help}"
shift || true
case "$cmd" in
  roles)
    roles
    ;;
  profile)
    profile "${1:-}"
    ;;
  wrapper)
    wrapper "${1:-}"
    ;;
  write)
    write_all "${1:-}"
    ;;
  help|--help|-h)
    usage
    ;;
  *)
    die "unknown command: $cmd"
    ;;
esac
